export function pickPuzzle(excludeIds: string[] = []): PinpointPuzzle {
  const unseen = PUZZLES.filter((puzzle) => !excludeIds.includes(puzzle.id));
  const pool = unseen.length > 0 ? unseen : PUZZLES;
  return pool[Math.floor(Math.random() * pool.length)];
}
